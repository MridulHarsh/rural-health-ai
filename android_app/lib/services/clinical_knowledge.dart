// clinical_knowledge.dart
// Curated clinical knowledge base for rural Indian healthcare context.
// This replaces ML-first diagnosis with doctor-like reasoning.

/// Body systems — the first filter a doctor applies.
enum BodySystem {
  respiratory,
  cardiac,
  gastrointestinal,
  neurological,
  dermatological,
  musculoskeletal,
  endocrine,
  infectious, // systemic infections (malaria, dengue, etc.)
  urogenital,
  hematological,
  maternal,
  ent, // ear-nose-throat
  ophthalmic,
}

/// How important a symptom is to a specific disease diagnosis.
enum SymptomRole {
  /// Almost always present. Absence seriously weakens the diagnosis.
  cardinal,

  /// Frequently present. Supports the diagnosis.
  common,

  /// Sometimes present. Mild supporting evidence.
  occasional,
}

/// Risk level output.
enum ClinicalRisk {
  emergency, // Immediate referral, life-threatening
  urgent, // Medical consultation within 24h
  moderate, // See a doctor soon (days)
  normal, // Home care, monitoring
}

/// Age-sex context for prevalence adjustment.
class Demographics {
  final int? minAge;
  final int? maxAge;
  final String? sex; // 'M', 'F', or null for both

  const Demographics({this.minAge, this.maxAge, this.sex});

  double matchScore(int? patientAge, String? patientSex) {
    double score = 1.0;

    if (patientAge != null) {
      if (minAge != null && patientAge < minAge!) score *= 0.3;
      if (maxAge != null && patientAge > maxAge!) score *= 0.3;
    }

    if (sex != null && patientSex != null && sex != patientSex) {
      score *= 0.1; // e.g., prostate disease in female → near-zero
    }

    return score;
  }
}

/// A single disease profile — how a textbook describes its presentation.
class DiseaseProfile {
  final String id;
  final String displayName;
  final BodySystem primarySystem;
  final List<BodySystem> secondarySystems;

  /// Symptom key → role. This is the core clinical knowledge.
  final Map<String, SymptomRole> symptomProfile;

  /// Base prevalence weight in rural India (0.0–1.0).
  /// 1.0 = extremely common (URI, gastroenteritis)
  /// 0.1 = rare but important (meningitis)
  final double prevalence;

  /// Default risk if diagnosed.
  final ClinicalRisk typicalRisk;

  /// Age/sex predisposition.
  final Demographics demographics;

  /// Actionable next steps for the health worker.
  final List<String> nextSteps;

  /// Brief one-line description for the health worker.
  final String description;

  const DiseaseProfile({
    required this.id,
    required this.displayName,
    required this.primarySystem,
    this.secondarySystems = const [],
    required this.symptomProfile,
    required this.prevalence,
    required this.typicalRisk,
    this.demographics = const Demographics(),
    required this.nextSteps,
    required this.description,
  });

  /// Count of cardinal symptoms in this profile.
  int get cardinalCount =>
      symptomProfile.values.where((r) => r == SymptomRole.cardinal).length;
}

/// A red-flag rule. If triggered, it overrides all scoring.
class RedFlagRule {
  final String id;
  final String conditionName;

  /// ALL of these must be present to trigger.
  final List<String> requiredSymptoms;

  /// ANY of these, if also present, strengthens the trigger.
  final List<String> supportingSymptoms;

  /// Minimum number of supporting symptoms needed (0 = required alone suffice).
  final int minSupportingNeeded;

  final ClinicalRisk risk;
  final String immediateAction;

  /// Optional demographics filter.
  final Demographics? demographics;

  const RedFlagRule({
    required this.id,
    required this.conditionName,
    required this.requiredSymptoms,
    this.supportingSymptoms = const [],
    this.minSupportingNeeded = 0,
    required this.risk,
    required this.immediateAction,
    this.demographics,
  });
}

